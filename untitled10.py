class MetalNutDataset(Dataset):
    def __init__(self, csv_path, image_size=IMAGE_SIZE):
        self.df = pd.read_csv(csv_path)
        self.image_size = image_size

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]

        # Load and preprocess image
        image = Image.open(row["image_path"]).convert("RGB")
        image = image.resize(
            (self.image_size, self.image_size),
            Image.Resampling.BILINEAR
        )

        image = np.asarray(image, dtype=np.float32) / 255.0
        image = torch.from_numpy(image).permute(2, 0, 1)

        label = torch.tensor(float(row["label"]), dtype=torch.float32)

        # Normal images have no defect bounding box
        box_cols = ["x_min", "y_min", "x_max", "y_max"]
        box_values = row[box_cols].to_numpy(dtype=np.float32)
        box_values = np.nan_to_num(box_values, nan=0.0)
        box = torch.tensor(box_values, dtype=torch.float32)

        return image, label, box

